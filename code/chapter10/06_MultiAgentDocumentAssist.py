"""
Интеллектуальный помощник по работе с документами для многоагентной совместной работы

Используйте два SimpleAgent для совместной работы:
- Агент1: эксперт по поиску GitHub.
- Агент2: эксперт по созданию документов.
"""
from hello_agents import SimpleAgent, HelloAgentsLLM
from hello_agents.tools import MCPTool
from dotenv import load_dotenv

# Загрузить переменные среды в файл .env
load_dotenv(dotenv_path="../HelloAgents/.env")

print("="*70)
print("Интеллектуальный помощник по работе с документами для многоагентной совместной работы")
print("="*70)

# ============================================================
# Агент 1: Эксперт по поиску на GitHub
# ============================================================
print("\n【Шаг 1】Создайте эксперта по поиску на GitHub...")

github_searcher = SimpleAgent(
    name="Эксперт по поиску на GitHub",
    llm=HelloAgentsLLM(),
    system_prompt="""Вы эксперт по поиску на GitHub.
Ваша задача — выполнить поиск в репозиториях GitHub и вернуть результаты.
Пожалуйста, возвращайте четкие, структурированные результаты поиска, в том числе:
- Название склада
- краткое описание

Держите его кратким и не добавляйте дополнительных объяснений."""
)

# Добавьте инструменты GitHub
github_tool = MCPTool(
    name="gh",
    server_command=["npx", "-y", "@modelcontextprotocol/server-github"]
)
github_searcher.add_tool(github_tool)

# ============================================================
# Агент 2: Эксперт по созданию документов
# ============================================================
print("\n【Шаг 2】Создайте эксперта по созданию документов...")

document_writer = SimpleAgent(
    name="Эксперт по формированию документов",
    llm=HelloAgentsLLM(),
    system_prompt="""Вы эксперт по созданию документов.
Ваша задача — создать структурированный отчет Markdown на основе предоставленной информации.

Отчет должен включать:
- титул
- Введение
- Основное содержание (перечислено в пунктах, включая название проекта, описание и т. д.)
- Резюме

Пожалуйста, выводите полное содержимое отчета напрямую в формате Markdown и не используйте инструменты для его сохранения."""
)

# Добавьте инструменты файловой системы
fs_tool = MCPTool(
    name="fs",
    server_command=["npx", "-y", "@modelcontextprotocol/server-filesystem", "."]
)
document_writer.add_tool(fs_tool)

# ============================================================
# выполнять задачи
# ============================================================
print("\n" + "="*70)
print("Начать миссию...")
print("="*70)

try:
    # Шаг 1. Поиск на GitHub
    print("\n【Шаг 3】Агент1 выполняет поиск на GitHub...")
    search_task = "Поиск в репозитории GitHub по запросу «Агент искусственного интеллекта» возвращает 5 наиболее релевантных результатов."
    
    search_results = github_searcher.run(search_task)
    
    print("\nРезультаты поиска:")
    print("-" * 70)
    print(search_results)
    print("-" * 70)
    
    # Шаг 2. Создайте отчет.
    print("\n【Шаг 4】Агент2 генерирует отчет...")
    report_task = f"""
Создайте отчет об исследовании в формате Markdown на основе следующих результатов поиска на GitHub:

{search_results}

Требования к отчетности:
1. Название: #Отчет об исследовании структуры агента AI
2. Введение. Объясните, что это исследование проекта GitHub по AI Agent.
3. Основные выводы: Перечислите найденные предметы и их характеристики (включая названия, описания и т. д.).
4. Резюме: суммируйте общие характеристики этих проектов.

Пожалуйста, выведите полный отчет в формате Markdown.
"""

    report_content = document_writer.run(report_task)

    print("\nСодержимое отчета:")
    print("=" * 70)
    print(report_content)
    print("=" * 70)

    # Шаг 3. Сохраните отчет
    print("\n【Шаг 5】Сохраните отчет в файл...")
    import os
    try:
        with open("report.md", "w", encoding="utf-8") as f:
            f.write(report_content)
        print("✅ Отчет сохранен на report.md")

        # Поверочные документы
        file_size = os.path.getsize("report.md")
        print(f"✅ Размер файла: {file_size} байт.")
    except Exception as e:
        print(f"❌ Не удалось сохранить: {e}.")
    
    print("\n" + "="*70)
    print("Миссия выполнена!")
    print("="*70)
    
except Exception as e:
    print(f"\n❌ Ошибка: {e}")
    import traceback
    traceback.print_exc()

