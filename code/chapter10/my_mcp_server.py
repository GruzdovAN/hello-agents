"""
Пример пользовательского сервера MCP

Это простой сервер MCP, который предоставляет базовые математические вычисления и инструменты обработки текста.
Используется для демонстрации того, как создать собственный сервер MCP.

Как запустить:
    Python my_mcp_server.py

Или вызывается клиентом как MCP-сервер:
    MCPClient(["python", "my_mcp_server.py"])
"""

from fastmcp import FastMCP
import sys
import os

# Создать экземпляр сервера MCP
mcp = FastMCP("MyCustomServer")


# ==================== Математические инструменты ===================

@mcp.tool()
def add(a: float, b: float) -> float:
    """
    Добавление калькулятора
    
    Аргументы:
        а: первое число
        б: второй номер
    
    Возврат:
        сумма двух чисел
    """
    return a + b


@mcp.tool()
def subtract(a: float, b: float) -> float:
    """
    Калькулятор вычитания
    
    Аргументы:
        а: уменьшать
        б: вычесть
    
    Возврат:
        разница между двумя числами
    """
    return a - b


@mcp.tool()
def multiply(a: float, b: float) -> float:
    """
    калькулятор умножения
    
    Аргументы:
        а: первое число
        б: второй номер
    
    Возврат:
        произведение двух чисел
    """
    return a * b


@mcp.tool()
def divide(a: float, b: float) -> float:
    """
    калькулятор деления
    
    Аргументы:
        а: дивиденд
        б: делитель
    
    Возврат:
        частное двух чисел
    
    Поднимает:
        ValueError: когда делитель равен 0
    """
    if b == 0:
        raise ValueError("Делитель не может быть нулем")
    return a / b


# ==================== Инструменты обработки текста ===================

@mcp.tool()
def reverse_text(text: str) -> str:
    """
    Обратный текст
    
    Аргументы:
        text: текст для инвертирования
    
    Возврат:
        перевернутый текст
    """
    return text[::-1]


@mcp.tool()
def count_words(text: str) -> int:
    """
    Посчитайте количество слов в тексте
    
    Аргументы:
        text: текст, который нужно посчитать
    
    Возврат:
        количество слов
    """
    return len(text.split())


@mcp.tool()
def to_uppercase(text: str) -> str:
    """
    Преобразовать текст в верхний регистр
    
    Аргументы:
        текст: текст, который нужно преобразовать
    
    Возврат:
        текст в верхнем регистре
    """
    return text.upper()


@mcp.tool()
def to_lowercase(text: str) -> str:
    """
    Преобразовать текст в нижний регистр
    
    Аргументы:
        текст: текст, который нужно преобразовать
    
    Возврат:
        строчный текст
    """
    return text.lower()


# ==================== Определение ресурса ===================

@mcp.resource("config://server")
def get_server_config() -> str:
    """
    Получить информацию о конфигурации сервера
    
    Возврат:
        Строка JSON для конфигурации сервера
    """
    import json
    config = {
        "name": "MyCustomServer",
        "version": "1.0.0",
        "tools_count": 8,
        "description": "Пример пользовательского сервера MCP"
    }
    return json.dumps(config, ensure_ascii=False, indent=2)


@mcp.resource("info://capabilities")
def get_capabilities() -> str:
    """
    Получить список возможностей сервера
    
    Возврат:
        Текстовое описание списка способностей
    """
    capabilities = """
Список возможностей сервера:

Математические расчеты:
- добавить: расчет сложения
- вычесть: расчет вычитания
- умножение: вычисление умножения
- делить: расчет деления

Обработка текста:
-verse_text: обратный текст
- count_words: подсчитать количество слов.
- to_uppercase: преобразовать в верхний регистр.
- to_lowercase: преобразовать в нижний регистр.

Ресурсы:
- config://server: конфигурация сервера
- info://capabilities: список возможностей (данный ресурс)
"""
    return capabilities.strip()


# ==================== Подскажите шаблон слова ===================

@mcp.prompt()
def math_helper() -> str:
    """
    Подсказки помощника по математическим расчетам
    
    Возврат:
        шаблон слова подсказки
    """
    return """Вы помощник по математическим расчетам. Вы можете использовать следующие инструменты:
- add(a, b): вычислить сумму двух чисел
- subtract(a, b): вычислить разницу между двумя числами.
- умножить(a, b): вычислить произведение двух чисел
- разделить(a, b): вычислить частное двух чисел

Пожалуйста, выберите подходящий инструмент для расчета в зависимости от проблемы пользователя."""


@mcp.prompt()
def text_processor() -> str:
    """
    Слова подсказки помощника по обработке текста
    
    Возврат:
        шаблон слова подсказки
    """
    return """Вы помощник по обработке текста. Вы можете использовать следующие инструменты:
-verse_text(text): обратный текст
- count_words(text): подсчитать количество слов.
- to_uppercase(text): преобразовать в верхний регистр.
- to_lowercase(text): преобразовать в нижний регистр.

Пожалуйста, выберите подходящий инструмент для обработки текста в соответствии с потребностями пользователя."""


# =================== Основная программа ===================

if __name__ == "__main__":
    # Запустить MCP-сервер
    # FastMCP автоматически обработает передачу stdio.
    mcp.run()

