        print("• 🎯 Оценка качества поиска")
        print("• 💾 Использование ресурсов")
        print("• 📈 Анализ масштабируемости")
        
        # Запрос теста производительности
        performance_queries = [
            "машинное обучение",
            "Алгоритм оптимизации глубокого обучения",
            "Принцип механизма внимания трансформатора",
            "Сравнение методов обнаружения целей компьютерного зрения"
        ]
        
        print(f"\n📊 Сравнительный тест производительности:")
        
        # Проверьте эффективность различных стратегий поиска.
        strategies = [
            ("Базовый поиск", {"enable_advanced_search": False}),
            ("Расширенный поиск", {"enable_advanced_search": True})
        ]
        
        performance_results = {}
        
        for strategy_name, params in strategies:
            print(f"\n{strategy_name}Тест производительности:")
            strategy_times = []
            
            for query in performance_queries:
                start_time = time.time()
                
                result = self.rag_tool.run({"action":"search",
                                             "query":query,
                                             "limit":3,
                                             **params})
                
                query_time = time.time() - start_time
                strategy_times.append(query_time)
                
                print(f"  Запрос: '{query[:20]}...' Занимает время: {query_time:.3f} секунд.")
            
            avg_time = sum(strategy_times) / len(strategy_times)
            performance_results[strategy_name] = {
                "times": strategy_times,
                "average": avg_time
            }
            
            print(f"  Среднее затраченное время: {avg_time:.3f} секунд.")
        
        # Сравнительный анализ производительности
        print(f"\n📈 Сравнительный анализ производительности:")
        basic_avg = performance_results["Базовый поиск"]["average"]
        advanced_avg = performance_results["Расширенный поиск"]["average"]
        
        print(f"Среднее время базового поиска: {basic_avg:.3f} секунд.")
        print(f"Среднее время расширенного поиска: {advanced_avg:.3f} секунд.")
        print(f"Коэффициент производительности: {advanced_avg/basic_avg:.1f}x")
        print(f"Анализ: расширенный поиск улучшает качество поиска за счет нескольких стратегий, а затраты времени увеличиваются {((advanced_avg/basic_avg-1)*100):.0f}%")
        
        # Получить системную статистику
        stats = self.rag_tool.run({"action":"stats"})
        print(f"\n📊 Системная статистика: {stats}")

