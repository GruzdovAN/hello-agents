    @classmethod
    def get_role_desc(cls, role: str) -> str:
        """Получить описание роли"""
        return cls.ROLES.get(role, {}).get("description", "неизвестная роль")
    
    @classmethod
    def get_role_ability(cls, role: str) -> str:
        """Получите навыки персонажа"""
        return cls.ROLES.get(role, {}).get("ability", "Никаких специальных навыков")
    
    @classmethod
    def get_character_trait(cls, character: str) -> str:
        """Получить черты характера"""
        return cls.CHARACTER_TRAITS.get(character, "Нежный характер и хорошая речь")
    
    @classmethod
    def is_werewolf(cls, role: str) -> bool:
        """Определите, являетесь ли вы оборотнем"""
        return role == "оборотень"
    
    @classmethod
    def is_villager_team(cls, role: str) -> bool:
        """Определите, находитесь ли вы в лагере хороших парней"""
        return cls.ROLES.get(role, {}).get("team") == "лагерь хороших ребят"
    
    @classmethod
    def get_standard_setup(cls, player_count: int) -> List[str]:
        """Получить стандартную конфигурацию роли"""
        if player_count == 6:
            return ["оборотень", "оборотень", "пророк", "ведьма", "сельский житель", "сельский житель"]
        elif player_count == 8:
            return ["оборотень", "оборотень", "оборотень", "пророк", "ведьма", "охотник", "сельский житель", "сельский житель"]
        elif player_count == 9:
            return ["оборотень", "оборотень", "оборотень", "пророк", "ведьма", "охотник", "опекун", "сельский житель", "сельский житель"]
        else:
            # Конфигурация по умолчанию: около 1/3 оборотня.
            werewolf_count = max(1, player_count // 3)
            roles = ["оборотень"] * werewolf_count
            
            # Добавить духовенство
            remaining = player_count - werewolf_count
            if remaining >= 1:
                roles.append("пророк")
                remaining -= 1
            if remaining >= 1:
                roles.append("ведьма")
                remaining -= 1
            if remaining >= 1:
                roles.append("охотник")
                remaining -= 1
            
            # Остальные - жители села
            roles.extend(["сельский житель"] * remaining)
            
            return roles