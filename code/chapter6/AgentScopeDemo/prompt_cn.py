# -*- coding: utf-8 -*-
"""Троецарствие: Оборотень, убивающий китайские слова"""

class ChinesePrompts:
    """Категория управления словами на китайском языке"""
    
    @staticmethod
    def get_role_prompt(role: str, character: str) -> str:
        """Получить подсказки для персонажей"""
        base_prompt = f"""Вы — {персонаж}, играющий {роль} в этой игре об убийстве оборотней «Троецарствие».

Пожалуйста, отвечайте строго в следующем формате JSON, не добавляя никакого другого текста:
{{
    «reach_agreement»: правда/ложь,
    «уровень_доверительности»: число от 1 до 10,
    "key_evidence": "Ваше доказательство или мнение"
}}

Характеристики персонажа:
"""
        
        if role == "оборотень":
            return base_prompt + f"""
- Вы оборотень и ваша цель уничтожить всех хороших парней
- Вы можете вести переговоры с другими оборотнями, чтобы убивать цели ночью.
- Скрывайте свою личность в течение дня и вводите в заблуждение хороших людей
- Говорите и действуйте как {персонаж}
"""
        elif role == "пророк":
            return base_prompt + f"""
- Вы пророк из лагеря хороших парней и ваша цель - найти всех оборотней.
- Истинную личность одного игрока можно проверять каждую ночь
- Необходимо аргументированно объявить результаты проверки и направить на голосование хороших людей.
- Анализируйте ситуации с мудростью и проницательностью {персонажа}.
"""
        elif role == "ведьма":
            return base_prompt + f"""
- Ты ведьма в лагере добра, и у тебя есть одна бутылочка противоядия и одна бутылочка с ядом.
- Противоядие может оживить игроков, убитых оборотнями.
-Яд может убить игрока
- Используйте реквизит осторожно и сделайте его полезным в критические моменты.
"""
        elif role == "охотник":
            return base_prompt + f"""
- Вы охотник из лагеря хороших парней.
- Может застрелить игрока, если его выгнали
- Используйте навыки в критические моменты, чтобы убрать оборотня
- Действуйте смело и решительно {character}
"""
        else:  # сельский житель
            return base_prompt + f"""
- Вы сельский житель из доброго лагеря
- Никаких особых навыков, только рассуждения и голосование.
- Внимательно наблюдайте, чтобы обнаружить недостатки оборотня.
- Участвуйте в обсуждениях как {character}
"""
