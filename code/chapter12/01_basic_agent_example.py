"""
Глава 12. Пример 1: Пример базового агента

Соответствующий документ: 12.1.1 Зачем нужна оценка агента

В этом примере показан базовый агент, который может вызвать инструмент поиска для выполнения задачи.
Но как мы узнаем, насколько хорошо он работает? Вот почему необходимы системы оценки.
"""

from hello_agents import SimpleAgent, HelloAgentsLLM
from hello_agents.tools import SearchTool

# Создайте LLM и агентов
llm = HelloAgentsLLM()

# Создайте системное слово, подчеркивающее использование инструмента.
system_prompt = """Вы — помощник искусственного интеллекта, который может использовать инструменты поиска для получения самой последней информации.

При необходимости поиска информации используйте следующий формат:
[TOOL_CALL:поиск:ключевое слово поиска]

Например:
- [TOOL_CALL:поиск:последние новости ИИ]
- [TOOL_CALL:search:Урок по программированию на Python]

Прежде чем ответить на вопрос, воспользуйтесь инструментом поиска, чтобы получить самую свежую информацию."""

agent = SimpleAgent(name="ИИ-помощник", llm=llm, system_prompt=system_prompt)

# Добавить инструмент поиска
agent.add_tool(SearchTool())

# Пример. Используйте инструмент поиска, чтобы ответить на вопрос.
print("\nВопрос: Какова последняя тенденция развития технологий искусственного интеллекта?")
print("\nАгент думает и ищет...")
response = agent.run("Каковы последние тенденции развития технологий искусственного интеллекта?")
print(f"\nОтвет: {ответ}")

