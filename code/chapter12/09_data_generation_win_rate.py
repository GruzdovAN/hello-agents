"""
Глава 12. Пример 9. Оценка процента выигрышей

Соответствующий документ: 12.4.4 Оценка процента побед.

В этом примере показано, как использовать процент побед для оценки качества сгенерированных вопросов AIME.

Оценка WinRate оценивает качество генерации путем сравнения сгенерированных вопросов и реальных вопросов:
- Процент побед = 50%: качество генерации соответствует качеству реальных вопросов (идеальная ситуация).
- Процент побед > 50%: качество генерации лучше, чем реальные вопросы (возможно, из-за предвзятости оценки)
- Процент побед < 50%: качество генерации ниже, чем в реальных вопросах (требует улучшения).
"""

import sys
import os
import json

# Добавить путь HelloAgents
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "HelloAgents"))

from hello_agents import HelloAgentsLLM
from hello_agents.evaluation import WinRateEvaluator, AIDataset

# 1. Подготовьте сгенерированные данные для вопросов.
generated_problems = [
    {
        "problem_id": "generated_001",
        "problem": "Find the number of positive integers $n$ such that $n^2 + 19n + 92$ is a perfect square.",
        "answer": "4"
    },
    {
        "problem_id": "generated_002",
        "problem": "In triangle $ABC$, $AB = 13$, $BC = 14$, and $CA = 15$. Find the area of the triangle.",
        "answer": "84"
    },
    {
        "problem_id": "generated_003",
        "problem": "How many positive integers less than 1000 are divisible by 7 but not by 11?",
        "answer": "129"
    }
]

# 2. Загрузите набор справочных данных (реальные вопросы AIME).
print("="*60)
print("Оценка выигрыша")
print("="*60)

print("\nЗагрузить набор справочных данных...")
dataset = AIDataset()
reference_problems = dataset.load()
print(f"✅ Загружены реальные вопросы AIME по {len(reference_problems)}")

# 3. Создайте оценщик винрейта
llm = HelloAgentsLLM(model_name="gpt-4o")
evaluator = WinRateEvaluator(
    llm=llm,
    reference_problems=reference_problems
)

# 4. Запустите оценку процента побед
print(f"\nНачать оценку процента побед...")
print(f"  Количество сгенерированных вопросов: {len(generated_problems)}")
print(f"  Количество сравнений: 20")

results = evaluator.evaluate(
    generated_problems=generated_problems,
    num_comparisons=20  # Сделайте 20 сравнений
)

# 5. Отображение результатов оценки
print("\n" + "="*60)
print("Результаты оценки")
print("="*60)

print(f"\nWin Rate: {results['win_rate']:.2%}")
print(f"Tie Rate: {results['tie_rate']:.2%}")
print(f"Loss Rate: {results['loss_rate']:.2%}")

print(f"\nПодробная статистика:")
print(f"  Общее количество сравнений: {results['total_comparisons']}")
print(f"  Создать выигрышные вопросы: {results['wins']}")
print(f"  Ничья: {results['ties']}")
print(f"  Реальный вопрос выигрывает: {results['losses']}")

# 6. Оценка качества
print(f"\nОценка качества:")
win_rate = results['win_rate']

if 0.45 <= win_rate <= 0.55:
    print("✅ Отлично - качество генерации близко к уровню реальных вопросов AIME")
elif 0.35 <= win_rate < 0.45:
    print("⚠️ Хорошо — качество генерации приемлемое, но немного ниже, чем у реальных тестовых вопросов.")
elif 0.25 <= win_rate < 0.35:
    print("⚠️ Удовлетворительно — качество сборки среднее и требует улучшения.")
else:
    print("❌ Плохое — качество сборки плохое и требует значительного улучшения.")

# 7. Просмотрите некоторые детали сравнения
print("\n" + "="*60)
print("Детали сравнения (топ-5)")
print("="*60)

for i, comparison in enumerate(results['comparisons'][:5], 1):
    print(f"\nСравнить {i}:")
    print(f"  Созданный вопрос: {сравнение['generated_problem'][:60]}...")
    print(f"  Настоящий вопрос: {сравнение['reference_problem'][:60]}...")
    print(f"  Результат: {сравнение['результат']}")
    if 'reason' in comparison:
        print(f"  Причина: {сравнение['причина'][:100]}...")

# 8. Сохранить результаты оценки
output_file = "./evaluation_results/win_rate_results.json"
os.makedirs(os.path.dirname(output_file), exist_ok=True)

with open(output_file, 'w', encoding='utf-8') as f:
    json.dump(results, f, indent=2, ensure_ascii=False)

print(f"\n ✅ Результаты экзамена сохранены в {output_file}")

