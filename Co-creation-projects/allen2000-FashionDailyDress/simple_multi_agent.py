    response += f"🧥 **Верхняя одежда**: {', '.join(base_advice['верхняя_одежда'][:2])}"
    
    if base_advice['аксессуары']:
        response += f", аксессуары: {', '.join(base_advice['аксессуары'][:3])}\n"
