def get_city_input():
    """Получить название города от пользователя"""
    print("💬 Добро пожаловать в мультиагентную систему рекомендаций по одежде по погоде!")
    print("💡 Введите название города, для которого хотите узнать погоду")
    print("💡 Поддерживаются русские и английские названия")
    print("💡 Введите 'quit' или 'выход' для завершения программы\n")
    
    while True:
        city = input("🌍 Введите название города: ").strip()
        if not city:
            print("❌ Введите корректное название города")
            continue
            
        return city

def get_real_weather(city_name):
    """Получить реальные погодные данные"""
    try:
        # Импорт класса Weather
        from weather import Weather
        
        # Создание экземпляра запроса погоды
        weather = Weather()
        
        # Запрос погодной информации
        weather_info = weather.get_weather(city_name)
        
        # Подробные данные для рекомендаций по одежде
        weather_details = weather.get_weather_details(city_name)
        
        return weather_info, weather_details
        
    except Exception as e:
        print(f"❌ Ошибка запроса погоды: {e}")
        # Возврат имитационных данных
        return f"🏙️ Город: {city_name}\n🌡️ Температура: 20°C\n📝 Погода: ясно\n💧 Влажность: 50%\n🌬️ Скорость ветра: 3 м/с", None

def get_llm_fashion_advice(weather_details, city_name):
    """Сформировать рекомендации по одежде через LLM на основе реальных погодных данных"""
    if weather_details and "error" not in weather_details:
        # Использование реальных погодных данных
        temp = weather_details.get('temperature', 20)
        description = weather_details.get('description', 'ясно')
        humidity = weather_details.get('humidity', 50)
        wind_speed = weather_details.get('wind_speed', 3)
        
        # Формирование промпта для LLM
        prompt = f"""
Дайте профессиональные рекомендации по одежде для города {city_name} на основе следующей погоды:
- Температура: {temp}°C
- Погодные условия: {description}
- Влажность: {humidity}%
- Скорость ветра: {wind_speed} м/с

Предоставьте подробные и практичные рекомендации, включая:
1. Выбор верхней одежды
2. Выбор нижней одежды
3. Рекомендации по обуви
4. Верхняя одежда / аксессуары
5. Особые меры предосторожности

Ответьте на русском языке, формат должен быть ясным и удобным для чтения."""
        
        # Имитация ответа LLM (в реальном приложении здесь вызывается API LLM)
        llm_response = simulate_llm_response(prompt, temp, description)
        
        return f"🤖 Рекомендации LLM по одежде (на основе реальных данных погоды для {city_name}):\n\n{llm_response}"
    else:
        # Использование имитационных данных
        prompt = f"""
Дайте профессиональные рекомендации по одежде для города {city_name} на основе следующей погоды:
- Температура: 20°C
- Погодные условия: ясно
- Влажность: 50%
- Скорость ветра: 3 м/с

Предоставьте подробные и практичные рекомендации."""
        
        llm_response = simulate_llm_response(prompt, 20, 'ясно')
        return f"🤖 Рекомендации LLM по одежде (на основе погодных данных для {city_name}):\n\n{llm_response}"

