"""
Агент рекомендаций по одежде
Специализируется на советах по одежде на основе погодной информации
"""
from hello_agents import SimpleAgent, HelloAgentsLLM
import os
from dotenv import load_dotenv

load_dotenv()

class FashionAgent:
    """Агент рекомендаций по одежде"""
    
    def __init__(self, name="Модный консультант"):
        """Инициализация агента рекомендаций по одежде"""
        self.name = name
        self.agent = SimpleAgent(
            name=name, 
            llm=HelloAgentsLLM(
                api_key=os.environ.get("LLM_API_KEY"),
                base_url=os.environ.get("LLM_BASE_URL"),
                model=os.environ.get("LLM_MODEL_ID")
            )
        )
        
        # Настройка системного промпта агента
        self._setup_prompt()
    
    def _setup_prompt(self):
        """Настройка системного промпта агента"""
        system_prompt = """Вы профессиональный модный консультант, специализирующийся на рекомендациях по одежде на основе погодной информации.

Ваши обязанности:
1. Давать подходящие рекомендации по одежде на основе погоды (температура, влажность, скорость ветра, погодные условия)
2. Учитывать потребности в одежде для разных сезонов, случаев и групп людей
3. Предлагать конкретные сочетания одежды: верх, низ, верхняя одежда, обувь и т.д.
4. Учитывать практические потребности: тепло, защита от солнца, дождя
5. Давать модные и практичные советы

Руководство по рекомендациям:
- Жаркая погода (>30°C): лёгкая дышащая одежда, защита от солнца
- Тёплая погода (20–30°C): комфортная однослойная одежда
- Прохладная погода (10–20°C): одежда с длинным рукавом, можно добавить лёгкую куртку
- Холодная погода (<10°C): тёплая одежда — свитер, пуховик и т.д.
- Дождь: водонепроницаемая верхняя одежда и дождевик
- Сильный ветер: ветрозащитная одежда

Давайте подробные и практичные рекомендации по одежде на основе конкретной погодной информации."""
        
        self.agent.system_prompt = system_prompt
    
    def get_fashion_advice(self, weather_info):
        """
        Получить рекомендации по одежде на основе погодной информации
        
        Args:
            weather_info: строка или словарь с погодной информацией
            
        Returns:
            строка с рекомендациями по одежде
        """
        # Формирование запроса
        query = f"""Дайте рекомендации по одежде на основе следующей погодной информации:

Погода:
{weather_info}

Предоставьте подробные рекомендации, включая:
1. Подходящие типы одежды
2. Конкретные советы по сочетанию
3. На что обратить внимание
4. Модные советы"""
        
        # Получение рекомендаций через агента
        response = self.agent.run(query)
        return response
    
    def get_detailed_fashion_advice(self, weather_data):
        """
        Получить более подробные рекомендации на основе структурированных погодных данных
        
        Args:
            weather_data: словарь с погодной информацией
            
        Returns:
            строка с подробными рекомендациями по одежде
        """
        if isinstance(weather_data, dict):
            # Извлечение ключевой информации из словаря
            temperature = weather_data.get('temperature', 'неизвестно')
            description = weather_data.get('description', 'неизвестно')
            humidity = weather_data.get('humidity', 'неизвестно')
            wind_speed = weather_data.get('wind_speed', 'неизвестно')
            
            query = f"""Дайте профессиональные рекомендации по одежде на основе следующих подробных погодных данных:

Подробная погода:
- Температура: {temperature}°C
- Погодные условия: {description}
- Влажность: {humidity}%
- Скорость ветра: {wind_speed} м/с

Предоставьте:
1. Подходящие материалы и типы одежды
2. Советы по многослойной одежде (для разных температур)
3. Рекомендации по аксессуарам (шапка, шарф, перчатки и т.д.)
4. Меры предосторожности при особых погодных условиях
5. Советы по модным сочетаниям"""
        else:
            query = f"Дайте рекомендации по одежде на основе следующей погодной информации:\n\n{weather_data}"
        
        response = self.agent.run(query)
        return response


def main():
    """Тестовая функция"""
    # Создание агента рекомендаций по одежде
    fashion_agent = FashionAgent()
    
    # Тестовые данные
    test_weather = """🏙️ Город: Shanghai
🌡️ Температура: 25°C
📝 Погода: ясно
💧 Влажность: 60%
🌬️ Скорость ветра: 3 м/с"""
    
    print("=== Тест агента рекомендаций по одежде ===")
    advice = fashion_agent.get_fashion_advice(test_weather)
    print(advice)


if __name__ == "__main__":
    main()
