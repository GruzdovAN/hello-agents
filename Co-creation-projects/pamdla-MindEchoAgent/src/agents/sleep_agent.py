# src/agents/sleep_agent.py

from hello_agents.protocols import A2AServer

# A2A-сервер: эксперт по сну
sleep_agent = A2AServer(
    name="sleep_agent",
    description="Эксперт по сну: рекомендации для засыпания и стратегии сна"
)

@sleep_agent.skill("answer")
def answer_sleep_question(text: str) -> str:
    # MVP: фиксированные стратегии (расширяемо)
    return (
        "Рекомендации для сна:\n"
        "1. Отключите электронные устройства, сделайте 5 минут глубокого дыхания\n"
        "2. Выберите мягкую музыку и уменьшите громкость\n"
        "3. При продолжающейся тревоге — записайте мысли и напишите 3 благодарности\n"
        "\n(Для более персональных советов опишите вашу ситуацию со сном)"
    )
