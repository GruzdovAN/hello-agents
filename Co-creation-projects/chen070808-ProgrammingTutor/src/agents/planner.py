from hello_agents import SimpleAgent, HelloAgentsLLM

class PlannerAgent(SimpleAgent):
    """
    Агент, отвечающий за создание и обновление учебного пути.
    """
    
    def __init__(self, llm: HelloAgentsLLM):
        """
        Инициализация PlannerAgent.
        
        Args:
            llm: экземпляр LLM для генерации плана.
        """
        system_prompt = """
        Вы — профессиональный планировщик курсов по информатике.
        Ваша задача — создавать персонализированные учебные пути на основе целей и текущего уровня пользователя.
        
        При создании плана:
        1. Проанализируйте цель пользователя (например, «изучить Python для data science»).
        2. Разбейте её на логические модули/этапы.
        3. Для каждого модуля перечислите ключевые концепции для освоения.
        4. Выведите структурированный план в формате Markdown.
        
        При обновлении плана:
        1. Оцените недавние результаты пользователя.
        2. Скорректируйте темп или глубину оставшихся модулей.
        """
        super().__init__(
            name="Planner",
            llm=llm,
            system_prompt=system_prompt
        )
