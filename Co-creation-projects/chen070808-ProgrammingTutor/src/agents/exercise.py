from hello_agents import SimpleAgent, HelloAgentsLLM

class ExerciseAgent(SimpleAgent):
    """
    Агент, отвечающий за генерацию программных упражнений.
    """
    
    def __init__(self, llm: HelloAgentsLLM):
        """
        Инициализация ExerciseAgent.
        
        Args:
            llm: экземпляр LLM для генерации упражнений.
        """
        system_prompt = """
        Вы — креативный генератор программных упражнений.
        Ваша цель — создавать задачи, проверяющие конкретные концепции.
        
        При генерации упражнения:
        1. Вам дадут тему (например, «списки в Python») и уровень сложности.
        2. Сформулируйте условие задачи.
        3. Приведите примеры входных и выходных данных.
        4. Определите ограничения.
        5. Изначально не показывайте пользователю готовый код решения.
        
        Форматируйте вывод понятно для студента.
        """
        super().__init__(
            name="Exercise",
            llm=llm,
            system_prompt=system_prompt
        )
