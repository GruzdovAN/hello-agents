def get_structure_requirements(level: int) -> str:
    """Получить требования к структуре для уровня"""
    requirements = {
        1: """
Структура Level 1 (подтема):
1. Введение (100-150 слов): контекст, важность, обзор статьи
2. Основная часть (400-600 слов): 2-4 подраздела по 200-300 слов каждый
3. Итоги и перспективы (100-150 слов): ключевые выводы, направления для размышления
        """,
        2: """
Структура Level 2 (раздел):
1. Вводная часть раздела (100 слов): связь с предыдущим, тема раздела
2. Основное содержание (400 слов): подробное изложение, минимум 1 конкретный пример
3. Краткий итог (100 слов): резюме ключевых пунктов раздела
        """,
        3: """
Структура Level 3 (детали):
1. Конкретное пояснение (100-150 слов): углубление в отдельный аспект
2. Пример или дополнение (100-150 слов): фрагмент кода или иллюстрация
        """
    }
    return requirements.get(level, requirements[3])

